package com.example.ui.auth

import android.content.Context
import android.content.ContextWrapper
import androidx.credentials.CredentialManager
import androidx.test.core.app.ApplicationProvider
import kotlinx.coroutines.test.runTest
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36])
class AuthManagerTest {

    private class MissingResourcePackageContext(base: Context) : ContextWrapper(base) {
        override fun getPackageName(): String = "com.example.missing.resources"
    }

    @Test
    fun resolveDefaultWebClientId_returns_generated_client_id_when_google_services_present() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val clientId = AuthManager.resolveDefaultWebClientId(context)

        assertNotNull("default_web_client_id should be generated by google-services plugin", clientId)
        assertTrue(clientId!!.endsWith(".apps.googleusercontent.com"))
    }

    @Test
    fun resolveDefaultWebClientId_returns_null_when_resource_missing() {
        val baseContext = ApplicationProvider.getApplicationContext<Context>()
        val missingContext = MissingResourcePackageContext(baseContext)

        val clientId = AuthManager.resolveDefaultWebClientId(missingContext)
        assertNull(clientId)
    }

    @Test
    fun onGoogleSignInClicked_reports_clear_error_when_client_id_missing() = runTest {
        val baseContext = ApplicationProvider.getApplicationContext<Context>()
        val missingContext = MissingResourcePackageContext(baseContext)
        val credentialManager = CredentialManager.create(baseContext)

        var receivedError: String? = null
        var authSucceeded = false

        AuthManager.onGoogleSignInClicked(
            context = missingContext,
            credentialManager = credentialManager,
            onAuthSuccess = { authSucceeded = true },
            onAuthError = { error -> receivedError = error },
            scope = this
        )

        assertFalse(authSucceeded)
        assertNotNull(receivedError)
        assertTrue(receivedError!!.contains("default_web_client_id"))
    }

    @Test
    fun attemptAutoSignIn_calls_onUnauthenticated_when_client_id_missing() = runTest {
        val baseContext = ApplicationProvider.getApplicationContext<Context>()
        val missingContext = MissingResourcePackageContext(baseContext)
        val credentialManager = CredentialManager.create(baseContext)

        var unauthenticatedCalled = false
        var authSucceeded = false

        AuthManager.attemptAutoSignIn(
            context = missingContext,
            credentialManager = credentialManager,
            onAuthSuccess = { authSucceeded = true },
            onUnauthenticated = { unauthenticatedCalled = true },
            scope = this
        )

        assertFalse(authSucceeded)
        assertEquals(true, unauthenticatedCalled)
    }
}
